#!/usr/bin/env node
/**
 * Copies the Phosphor icons the app uses (https://phosphoricons.com, MIT License) into
 * apps/web/src/components/ui/phosphor.ts, in the three weights it draws them in: regular, bold
 * and fill. Only these are bundled, so the app doesn't ship Phosphor's other weights or the icons
 * it doesn't use. The names come from ICONS in apps/web/src/components/ui/Icon.tsx; after adding
 * one there, run:
 *   npm run icons
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ui = join(dirname(fileURLToPath(import.meta.url)), "../apps/web/src/components/ui");
const require = createRequire(join(ui, "Icon.tsx"));
const WEIGHTS = ["regular", "bold", "fill"];

const source = readFileSync(join(ui, "Icon.tsx"), "utf8");
const map = source.match(/\nconst ICONS = \{\n([\s\S]*?)\n\} satisfies/);
if (!map) throw new Error("Couldn't find `const ICONS = { ... } satisfies` in Icon.tsx");
const names = [...new Set([...map[1].matchAll(/^\s+\w+: "([a-z0-9-]+)",/gm)].map((m) => m[1]))].sort();

const { version } = JSON.parse(readFileSync(join(dirname(require.resolve("@phosphor-icons/core/assets/regular/house.svg")), "../../package.json"), "utf8"));
const missing = [];
const drawing = (name, weight) => {
  try {
    const svg = readFileSync(require.resolve(`@phosphor-icons/core/assets/${weight}/${name}${weight === "regular" ? "" : `-${weight}`}.svg`), "utf8");
    return svg.trim().replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  } catch {
    missing.push(`${name} (${weight})`);
    return "";
  }
};
const lines = names.map((name) => `  ${JSON.stringify(name)}: { ${WEIGHTS.map((w) => `${w}: ${JSON.stringify(drawing(name, w))}`).join(", ")} },`);
if (missing.length) {
  console.error(`Phosphor ${version} has no ${missing.join(", ")}. Check the name at https://phosphoricons.com.`);
  process.exit(1);
}

writeFileSync(
  join(ui, "phosphor.ts"),
  `/*! @license Phosphor Icons ${version} - MIT License, Copyright (c) 2023 Phosphor Icons - https://github.com/phosphor-icons/core */
// Generated by scripts/icons.mjs (npm run icons) from @phosphor-icons/core: the icons Icon.tsx names,
// each in the weights it draws. Do not edit by hand. The comment above stays in the built app, as
// Phosphor's license asks.

export const PHOSPHOR = {
${lines.join("\n")}
};

export type PhosphorName = keyof typeof PHOSPHOR;
`,
);
console.log(`Wrote ${names.length} icons to apps/web/src/components/ui/phosphor.ts`);
